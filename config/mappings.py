def get_nhanes_code(ques_id: str) -> str:
    """
    Convert question ID to NHANES code.
    
    Args:
        ques_id: String question ID (e.g., "10740")
        
    Returns:
        NHANES code (e.g., "HUQ051") or None if not found
    """
    try:
        ques_id_int = int(ques_id)
        return QUESTION_ID_MAPPING.get(ques_id_int)
    except (ValueError, TypeError):
        return None